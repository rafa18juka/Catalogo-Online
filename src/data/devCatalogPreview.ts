function imageUrl(tags: string, lock: number, size = '900/900') {
  return `https://loremflickr.com/${size}/${tags}?lock=${lock}`
}

function formatPrice(index: number, collectionIndex: number) {
  const value = 990 + collectionIndex * 220 + index * 370
  const reais = Math.floor(value / 100)
  const cents = String(value % 100).padStart(2, '0')

  return `R$ ${reais},${cents}`
}

function createProduct(
  collection: CollectionSeed,
  collectionIndex: number,
  name: string,
  productIndex: number,
): DevCatalogPreviewProduct {
  const sequence = collectionIndex * 100 + productIndex + 1
  const lock = 10000 + collectionIndex * 1000 + productIndex * 10
  const skuPrefix = collection.id
    .split('-')
    .map((part) => part[0])
    .join('')
    .toUpperCase()
    .slice(0, 3)
  const images = [
    imageUrl(collection.imageTags, lock),
    imageUrl(collection.imageTags, lock + 1),
    imageUrl(collection.imageTags, lock + 2),
  ]

  return {
    id: `dev-${collection.id}-${String(productIndex + 1).padStart(2, '0')}`,
    collectionId: collection.id,
    collectionName: collection.name,
    title: name,
    sku: `${skuPrefix}-${String(productIndex + 1).padStart(3, '0')}`,
    internalCode: `${skuPrefix}-INT-${String(sequence).padStart(4, '0')}`,
    category: collection.name,
    description: `${name} da colecao ${collection.name}, pensado para venda B2B com boa leitura visual, reposicao simples e composicao em kits comerciais.`,
    ean: `789845${String(100000 + sequence).padStart(6, '0')}`,
    ncm: collection.ncm,
    measurements: `${18 + (productIndex % 5) * 4} x ${
      12 + (productIndex % 4) * 3
    } x ${6 + (productIndex % 3) * 4} cm`,
    weight: `${90 + productIndex * 35} g`,
    masterBox: `${12 + (productIndex % 5) * 6} unidades`,
    minimumOrder: `${2 + (productIndex % 6) * 2} unidades`,
    observations:
      productIndex % 3 === 0
        ? 'Item recomendado para destaque de vitrine e kits promocionais.'
        : 'Produto cadastrado para simulacao completa do catalogo Aurora.',
    variations:
      productIndex % 2 === 0
        ? 'Natural, areia, verde'
        : 'Branco, grafite, sortido',
    stock: `${48 + collectionIndex * 7 + productIndex * 9} unidades`,
    status: productIndex % 11 === 0 ? 'Reposicao' : 'Disponivel',
    price: formatPrice(productIndex, collectionIndex),
    image: images[0],
    images,
    attention: 55 + ((collectionIndex + productIndex) % 40),
    sourceFichaPath: `src/data/devCatalogPreview.ts/${collection.id}/${String(
      productIndex + 1,
    ).padStart(2, '0')}`,
  }
}

export const devCatalogCollections: DevCatalogCollection[] = collectionSeeds.map(
  (collection, collectionIndex) => ({
    ...collection,
    heroImage: imageUrl(collection.imageTags, 50000 + collectionIndex, '1200/900'),
    products: collection.productNames.map((name, productIndex) =>
      createProduct(collection, collectionIndex, name, productIndex),
    ),
  }),
)

export const devCatalogPreviewProducts = devCatalogCollections.flatMap(
  (collection) => collection.products,
)
